type ProvenanceMetadata = Pick<
  Place,
  "dataStatus" | "sources" | "priceSourceType" | "openingHoursSourceType" | "lastVerifiedAt" | "scoreSource"
>;

function businessMetadata(source?: PlaceSource): ProvenanceMetadata {
  return {
    dataStatus: source ? "PARTIAL" : "ESTIMATED",
    sources: source ? [source] : [],
    priceSourceType: "EDITORIAL_ESTIMATE",
    openingHoursSourceType: source?.supportedFields.includes("OPENING_HOURS") ? "THIRD_PARTY" : "ESTIMATED",
    lastVerifiedAt: LAST_VERIFIED_AT,
    scoreSource: "EDITORIAL",
  };
}

function publicSpaceMetadata(source?: PlaceSource): ProvenanceMetadata {
  return {
    dataStatus: source ? "PARTIAL" : "ESTIMATED",
    sources: source ? [source] : [],
    priceSourceType: "NOT_APPLICABLE",
    openingHoursSourceType: "NOT_APPLICABLE",
    lastVerifiedAt: LAST_VERIFIED_AT,
    scoreSource: "EDITORIAL",
  };
}

function dailyHours(
  open: string,
  close: string,
  breakStart?: string,
  breakEnd?: string,
): OpeningHour[] {
  return [1, 2, 3, 4, 5, 6, 0].map((dayOfWeek) => ({
    dayOfWeek,
    open,
    close,
    ...(breakStart && breakEnd ? { breakStart, breakEnd } : {}),
  }));
}

function variedHours(
  weekday: { open: string; close: string; breakStart?: string; breakEnd?: string },
  weekend: { open: string; close: string; breakStart?: string; breakEnd?: string },
): OpeningHour[] {
  return [1, 2, 3, 4, 5, 6, 0].map((dayOfWeek) => {
    const hours = dayOfWeek === 0 || dayOfWeek === 6 ? weekend : weekday;
    return { dayOfWeek, ...hours };
  });
}

